"""Training pipeline.

Two model families are trained on purpose:

1. **XGBoost (supervised)** learns the *known* fraud typologies from labels.
   High precision on patterns seen before; blind to anything new.

2. **Isolation Forest (unsupervised)** is fitted on legitimate transactions only.
   It flags whatever looks statistically unusual for an account, even with no
   label anywhere near it. Noisier alone, which is why it carries a 0.25 weight.

The hybrid engine in ``app/ml/risk_engine.py`` blends both with auditable rules.
A single model, however good, is not what real fraud systems run.

Run:
    python scripts/generate_dataset.py
    python -m app.ml.train
"""
from __future__ import annotations

import argparse
import json
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
import xgboost as xgb
from sklearn.ensemble import IsolationForest

from app.core.config import settings
from app.core.logging import configure_logging, get_logger
from app.ml.dataset import DatasetError, describe_dataset, load_transactions_csv
from app.ml.evaluate import binary_metrics, feature_importance, precision_recall_curve_points
from app.ml.features import FEATURE_ORDER
from app.ml.model_store import save_model_bundle
from app.ml.preprocessing import (
    build_feature_table,
    class_balance,
    clean_feature_frame,
    temporal_split,
)
from app.ml.risk_engine import combine_scores, decide, normalize_anomaly_score, rule_heuristic_score

logger = get_logger(__name__)

MODEL_VERSION = "1.0.0"
PR_CURVE_SAMPLE = 8000

DATASET_LIMITATIONS = [
    "The default dataset is generated by this project, so its fraud typologies are known "
    "to the model by construction; metrics on it are an upper bound, not a real-world estimate.",
    "Fraud is heavily imbalanced ((~1%), which is why accuracy is not reported as a headline metric "
    "and PR-AUC / recall are used instead.",
    "The dataset contains no authentication or device telemetry, so nothing here measures the "
    "contribution of security-event correlation; that is evaluated in the Defense Comparison Lab.",
]


def train_supervised(X_train: np.ndarray, y_train: np.ndarray, X_val: np.ndarray, y_val: np.ndarray):
    """Fit the supervised classifier, weighting the minority class."""
    scale_pos_weight = float((y_train == 0).sum()) / max(float((y_train == 1).sum()), 1.0)
    model = xgb.XGBClassifier(
        n_estimators=400,
        max_depth=5,
        learning_rate=0.05,
        subsample=0.85,
        colsample_bytree=0.85,
        scale_pos_weight=scale_pos_weight,
        eval_metric="aucpr",
        reg_lambda=1.0,
        n_jobs=-1,
        random_state=settings.default_seed,
    )
    model.fit(X_train, y_train, eval_set=[(X_val, y_val)], verbose=False)
    return model


def train_unsupervised(X_train_legit: np.ndarray):
    """Fit the anomaly detector on legitimate rows only."""
    model = IsolationForest(
        n_estimators=300,
        contamination=0.02,
        random_state=settings.default_seed,
        n_jobs=-1,
    )
    model.fit(X_train_legit)
    return model


def evaluate_pipelines(
    test_frame: pd.DataFrame,
    xgb_model,
    iso_model,
    calibration: dict,
) -> dict:
    """Measure each detection configuration on the same held-out test slice.

    All three configurations are scored *exactly* as they are online:

    * ``rule_based``          rules only (what a rules-only defense catches)
    * ``transaction_only``    ML on transaction features, no security events
    * ``combined``            rules + both ML models (the default configuration)

    Security-event correlation is a separate component and is measured by the
    Defense Comparison Lab against simulated scenarios, where security events
    actually exist.
    """
    X = test_frame[FEATURE_ORDER].to_numpy(dtype=float)
    y = test_frame["is_fraud"].to_numpy(dtype=int)

    supervised = xgb_model.predict_proba(X)[:, 1]
    anomaly_raw = iso_model.score_samples(X)
    anomaly = np.array([normalize_anomaly_score(value, calibration) for value in anomaly_raw])

    rule_rows = [
        rule_heuristic_score(dict(zip(FEATURE_ORDER, row)))
        for row in X
    ]
    rule_scores = np.array([row[0] for row in rule_rows])
    combined_scores = np.array([
        combine_scores(rule_scores[i], float(supervised[i]), float(anomaly[i]))
        for i in range(len(X))
    ])

    block = settings.thresholds.block_threshold
    flag = settings.thresholds.flag_threshold

    return {
        "rule_based": {
            **binary_metrics(y, rule_scores, threshold=flag),
            "description": "Heuristic rules only, no ML and no security events.",
        },
        "transaction_only": {
            **binary_metrics(y, supervised, threshold=0.5),
            "description": "XGBoost on transaction features only.",
            "pr_curve": precision_recall_curve_points(y, supervised),
        },
        "combined": {
            **binary_metrics(y, combined_scores, threshold=flag),
            "description": "Blended risk score (rules + supervised + anomaly) at the FLAG threshold.",
            "block_threshold": block,
            "flag_threshold": flag,
            "decisions": {
                "ALLOW": int((combined_scores < flag).sum()),
                "FLAG": int(((combined_scores >= flag) & (combined_scores < block)).sum()),
                "BLOCK": int((combined_scores >= block).sum()),
            },
            "pr_curve": precision_recall_curve_points(y, combined_scores),
        },
        "anomaly_only": {
            **binary_metrics(y, anomaly, threshold=0.5),
            "description": "Isolation Forest only, trained without labels.",
        },
    }


def register_model_versions(metrics: dict, model_dir: Path) -> None:
    """Record the artefacts in the database so the UI can show model history.

    Failing to register is not fatal for training, so this logs and continues when
    the database is unavailable (for example when training inside a bare container).
    """
    try:  # pragma: no cover - exercised via integration tests instead
        from app.core.config import settings as _settings  # noqa: F401
        from app.db.models import ModelVersion
        from app.db.session import SessionLocal, init_db

        init_db()
        session = SessionLocal()
        try:
            session.query(ModelVersion).filter(ModelVersion.is_active.is_(True)).update(
                {"is_active": False}
            )
            session.add_all([
                ModelVersion(
                    id=f"MODEL-XGB-{int(time.time())}",
                    name="xgboost",
                    version=MODEL_VERSION,
                    artifact_path=str(model_dir / "xgb_model.joblib"),
                    trained_at=datetime.now(timezone.utc).replace(tzinfo=None),
                    training_rows=int(metrics.get("train_rows", 0)),
                    feature_order=FEATURE_ORDER,
                    metrics=metrics.get("xgboost", {}),
                    is_active=True,
                    notes=metrics.get("xgboost", {}).get("description", ""),
                ),
                ModelVersion(
                    id=f"MODEL-ISO-{int(time.time())}",
                    name="isolation_forest",
                    version=MODEL_VERSION,
                    artifact_path=str(model_dir / "iso_forest.joblib"),
                    trained_at=datetime.now(timezone.utc).replace(tzinfo=None),
                    training_rows=int(metrics.get("train_rows", 0)),
                    feature_order=FEATURE_ORDER,
                    metrics=metrics.get("anomaly_only", {}),
                    is_active=True,
                    notes="Unsupervised detector fitted on legitimate transactions only.",
                ),
            ])
            session.commit()
        finally:
            session.close()
    except Exception as exc:
        logger.warning("Could not register model versions in the database: %s", exc)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Train the RupeeShield detection models.")
    parser.add_argument("--transactions", type=Path, default=settings.data_dir / "transactions.csv")
    parser.add_argument("--features-out", type=Path, default=settings.data_dir / "feature_table.parquet")
    parser.add_argument("--model-dir", type=Path, default=settings.model_dir)
    parser.add_argument("--test-fraction", type=float, default=0.25)
    parser.add_argument("--paysim", action="store_true", help="Treat the input file as a PaySim CSV.")
    parser.add_argument("--no-register", action="store_true", help="Skip database registration.")
    args = parser.parse_args(argv)

    configure_logging()

    try:
        if args.paysim:
            from app.ml.dataset import load_paysim_csv

            raw = load_paysim_csv(args.transactions)
            source = "paysim"
        else:
            raw = load_transactions_csv(args.transactions)
            source = "synthetic"
    except DatasetError as exc:
        logger.error("%s", exc)
        return 2

    logger.info("Loaded %s rows from %s", f"{len(raw):,}", args.transactions)

    feature_table = clean_feature_frame(build_feature_table(raw))
    args.features_out.parent.mkdir(parents=True, exist_ok=True)
    # Convenience dump only -- nothing downstream reads this file back. Parquet needs
    # an optional engine (pyarrow/fastparquet), so skip the dump rather than abort
    # training when neither is installed (e.g. a minimal CI environment).
    try:
        feature_table.to_parquet(args.features_out, index=False)
        logger.info("Feature table -> %s %s", args.features_out, feature_table.shape)
    except ImportError:
        logger.info(
            "Feature table not dumped to %s (no parquet engine installed); "
            "training continues.",
            args.features_out,
        )

    train_frame, test_frame = temporal_split(feature_table, args.test_fraction)
    logger.info(
        "Temporal split: %s train rows (up to %s) | %s test rows",
        f"{len(train_frame):,}", train_frame["timestamp"].max(), f"{len(test_frame):,}",
    )

    X_train = train_frame[FEATURE_ORDER].to_numpy(dtype=float)
    y_train = train_frame["is_fraud"].to_numpy(dtype=int)
    X_test = test_frame[FEATURE_ORDER].to_numpy(dtype=float)
    y_test = test_frame["is_fraud"].to_numpy(dtype=int)

    # The validation slice for early stopping is the tail of the training window,
    # never the test window -- using the test set here would leak it into training.
    inner_cut = int(len(X_train) * 0.8)
    xgb_model = train_supervised(
        X_train[:inner_cut], y_train[:inner_cut], X_train[inner_cut:], y_train[inner_cut:]
    )
    logger.info("XGBoost trained on %s rows", f"{inner_cut:,}")

    legit_mask = y_train == 0
    iso_model = train_unsupervised(X_train[legit_mask])
    logger.info("Isolation Forest fitted on %s legitimate rows", f"{int(legit_mask.sum()):,}")

    # Calibrate the anomaly score against the ACTUAL legitimate distribution.
    legit_anomaly = -iso_model.score_samples(X_train[legit_mask])
    calibration = {
        "p50": float(np.percentile(legit_anomaly, 50)),
        "p99": float(np.percentile(legit_anomaly, 99)),
    }
    logger.info("Anomaly calibration from legitimate training data: %s", calibration)

    supervised_metrics = {
        **binary_metrics(y_test, xgb_model.predict_proba(X_test)[:, 1], threshold=0.5),
        "description": "XGBoost on transaction features only (held-out test window).",
        "importance": feature_importance(xgb_model, FEATURE_ORDER),
        "pr_curve": precision_recall_curve_points(y_test, xgb_model.predict_proba(X_test)[:, 1]),
    }
    logger.info(
        "XGBoost test: PR-AUC=%s recall=%s precision=%s",
        supervised_metrics["pr_auc"], supervised_metrics["recall"], supervised_metrics["precision"],
    )

    pipelines = evaluate_pipelines(test_frame, xgb_model, iso_model, calibration)

    metrics = {
        "version": MODEL_VERSION,
        "trained_at": datetime.now(timezone.utc).replace(tzinfo=None).isoformat() + "Z",
        "dataset": describe_dataset(raw, source=source, path=args.transactions).to_dict(),
        "feature_order": FEATURE_ORDER,
        "train_rows": int(len(train_frame)),
        "test_rows": int(len(test_frame)),
        "class_balance": {
            "train": class_balance(train_frame["is_fraud"]),
            "test": class_balance(test_frame["is_fraud"]),
        },
        "calibration": calibration,
        "split_strategy": (
            "Temporal split (train on the earlier 75% of transactions, test on the later 25%). "
            "A random split would leak post-fraud-burst behaviour into training."
        ),
        "xgboost": {**supervised_metrics, **pipelines["transaction_only"]},
        "isolation_forest": {**pipelines["anomaly_only"], "calibration": calibration},
        "combined": pipelines["combined"],
        "rule_based": pipelines["rule_based"],
        "limitations": DATASET_LIMITATIONS,
    }

    paths = save_model_bundle(
        xgb_model, iso_model, FEATURE_ORDER, calibration, metrics, directory=args.model_dir
    )
    logger.info("Saved model artefacts to %s", paths["xgb"].parent)

    summary_path = args.model_dir / "training_summary.json"
    with open(summary_path, "w", encoding="utf-8") as handle:
        json.dump(
            {
                "combined": {k: v for k, v in metrics["combined"].items() if k != "pr_curve"},
                "isolation_forest": {
                    k: v for k, v in metrics["isolation_forest"].items()
                },
                "rule_based": metrics["rule_based"],
            },
            handle,
            indent=2,
        )

    if not args.no_register:
        register_model_versions(metrics, args.model_dir)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
